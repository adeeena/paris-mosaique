export const DICTIONARIES: Record<Language, Messages> = { en: EN, fr: FR, hu: HU };

const current = signal<Language>('en');

/** The language the texts are in; reading it inside an effect or a template follows language changes. */
export const language = current.asReadonly();

export function setLanguage(next: Language): void {
  current.set(next);
}

export function isLanguage(value: unknown): value is Language {
  return LANGUAGES.some(l => l.id === value);
}

export function t(key: MessageKey, params?: Record<string, string | number | undefined>): string {
  const text = DICTIONARIES[current()][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}
